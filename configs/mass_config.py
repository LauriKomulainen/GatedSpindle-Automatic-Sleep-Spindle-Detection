def get_explicit_splits(scorer_mode: str, repeat_idx: int) -> list:
    """Return explicit folds for the given scorer and repeat (0-indexed).

    Raises ValueError if the requested combination is not defined or if the
    splits fail validation against the eligible subject set for the scorer.
    """
    if scorer_mode not in MASS_SS_5FOLD_SPLITS:
        raise ValueError(
            f"No explicit splits defined for scorer_mode='{scorer_mode}'. "
            f"Available: {sorted(MASS_SS_5FOLD_SPLITS.keys())}"
        )

    repeat_key = f"Repeat_{repeat_idx + 1}"
    scorer_block = MASS_SS_5FOLD_SPLITS[scorer_mode]

    if repeat_key not in scorer_block:
        raise ValueError(
            f"No explicit splits defined for scorer_mode='{scorer_mode}', "
            f"{repeat_key}. Available: {sorted(scorer_block.keys())}"
        )

    folds = scorer_block[repeat_key]
    if not folds:
        raise ValueError(
            f"Splits for scorer_mode='{scorer_mode}', {repeat_key} are empty."
        )

    eligible = set(get_subjects_for_scorer(scorer_mode))
    seen_in_test = []

    for i, fold in enumerate(folds):
        for split_name in ('train', 'val', 'test'):
            if split_name not in fold:
                raise ValueError(
                    f"Fold {i + 1} for {scorer_mode}/{repeat_key} missing '{split_name}' key."
                )

        all_in_fold = set(fold['train']) | set(fold['val']) | set(fold['test'])
        not_eligible = all_in_fold - eligible
        if not_eligible:
            raise ValueError(
                f"Fold {i + 1} for {scorer_mode}/{repeat_key} contains subjects "
                f"not eligible for scorer '{scorer_mode}': {sorted(not_eligible)}"
            )

        # Disjointness check
        train_set, val_set, test_set = set(fold['train']), set(fold['val']), set(fold['test'])
        if train_set & val_set or train_set & test_set or val_set & test_set:
            raise ValueError(
                f"Fold {i + 1} for {scorer_mode}/{repeat_key} has overlapping splits."
            )

        seen_in_test.extend(fold['test'])

    # CV coverage: every eligible subject should appear in test exactly once
    test_counts = {s: seen_in_test.count(s) for s in eligible}
    not_tested = [s for s, c in test_counts.items() if c == 0]
    multi_tested = [s for s, c in test_counts.items() if c > 1]
    if not_tested or multi_tested:
        raise ValueError(
            f"CV coverage error for {scorer_mode}/{repeat_key}: "
            f"never tested={not_tested}, tested multiple times={multi_tested}"
        )

    return folds